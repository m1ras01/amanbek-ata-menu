export function t(lang: Lang, key: string): string {
  return UI[lang][key] ?? UI.ru[key] ?? key;
}

export function detectLang(acceptLanguage?: string | null): Lang {
  if (!acceptLanguage) return "ru";
  const lower = acceptLanguage.toLowerCase();
  if (lower.includes("kk") || lower.includes("kz")) return "kz";
  if (lower.includes("uz")) return "uz";
  if (lower.includes("ru")) return "ru";
  return "ru";
}

export function formatPrice(price: number): string {
  return `${price.toLocaleString("ru-RU")} ₸`;
}
